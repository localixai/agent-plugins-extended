/**
 * The verification ledger: every requirement checked by a reader against its docs section, and
 * every judgment re-examined. Each pass writes one file in `extend/conformance/verification/`:
 *
 *   { "pass": "<name>", "date": "YYYY-MM-DD", "release": "2.1.321", "files": ["04-skills.md"],
 *     "requirements": [{ "id", "file", "status": "verified" | "fixed" | "deviates", "note" }],
 *     "judgments": [{ "id": "J4.3", "status": "kept" | "fixed" | "removed" | "promoted", "note" }] }
 *
 * `verified`: the text states the requirement as the docs do. `fixed`: it did not, and the pass
 * corrected it (the note says how). `deviates`: E4a applies and the evidence was re-checked. This
 * script writes `extend/conformance/VERIFIED.md`; `--check` fails on an unknown id, an unknown
 * status, or a stale report. It never fails because verification is incomplete: that is progress.
 *
 *   bun run verification [--check]
 */
import { readdir } from 'node:fs/promises'
import { join } from 'node:path'
import { CONFORMANCE } from './paths.ts'

interface Entry { readonly id: string; readonly file?: string; readonly status: string; readonly note?: string }
interface Pass {
  readonly pass: string
  readonly date: string
  readonly files: readonly string[]
  readonly requirements: readonly Entry[]
  readonly judgments: readonly Entry[]
}

const REQUIREMENT_STATUS = new Set(['verified', 'fixed', 'deviates'])
const JUDGMENT_STATUS = new Set(['kept', 'fixed', 'removed', 'promoted'])
const LEDGER = join(CONFORMANCE, 'verification')

const { requirements } = (await Bun.file(join(CONFORMANCE, 'requirements.json')).json()) as {
  requirements: { id: string; category: string }[]
}
const known = new Set(requirements.map((each) => each.id))
const names = (await readdir(LEDGER).catch(() => [])).filter((name) => name.endsWith('.json')).sort()
const passes = await Promise.all(names.map(async (name) => (await Bun.file(join(LEDGER, name)).json()) as Pass))

const problems: string[] = []
const checked = new Map<string, string>()
let judgments = 0
const tally = new Map<string, number>()
for (const pass of passes) {
  for (const entry of pass.requirements ?? []) {
    if (!known.has(entry.id)) problems.push(`${pass.pass}: unknown id ${entry.id}`)
    if (!REQUIREMENT_STATUS.has(entry.status)) problems.push(`${pass.pass}: ${entry.id}: status ${entry.status}`)
    checked.set(entry.id, entry.status)
    tally.set(entry.status, (tally.get(entry.status) ?? 0) + 1)
  }
  for (const entry of pass.judgments ?? []) {
    if (!JUDGMENT_STATUS.has(entry.status)) problems.push(`${pass.pass}: ${entry.id}: status ${entry.status}`)
    judgments += 1
    tally.set(`judgment ${entry.status}`, (tally.get(`judgment ${entry.status}`) ?? 0) + 1)
  }
}
if (problems.length > 0) {
  console.error('Verification ledger problems:')
  for (const line of problems) console.error(`  ${line}`)
  process.exit(1)
}

const byCategory = new Map<string, { all: number; done: number }>()
for (const { id, category } of requirements) {
  const row = byCategory.get(category) ?? { all: 0, done: 0 }
  row.all += 1
  if (checked.has(id)) row.done += 1
  byCategory.set(category, row)
}
const missing = requirements.filter(({ id }) => !checked.has(id)).map(({ id }) => id)
const report = [
  '# Verification report',
  '',
  'Generated by `bun run verification` from the ledgers in `verification/`; do not edit. A',
  'requirement is verified when a reader checked the text that states it against its docs',
  'section (or re-checked the evidence of a deviation, E4a).',
  '',
  `**Verified: ${checked.size} of ${requirements.length} requirements; ${judgments} judgments re-examined.**`,
  '',
  '| Outcome | Count |',
  '| --- | ---: |',
  ...[...tally].sort().map(([status, count]) => `| ${status} | ${count} |`),
  '',
  '| Category | Verified | Total |',
  '| --- | ---: | ---: |',
  ...[...byCategory].sort(([a], [b]) => a.localeCompare(b)).map(([name, { all, done }]) => `| ${name} | ${done} | ${all} |`),
  '',
  '## Passes',
  '',
  ...passes.map((pass) => `- \`${pass.pass}\` (${pass.date}): ${pass.files.join(', ')}`),
  '',
  `## Not verified yet (${missing.length})`,
  '',
  ...(missing.length > 40 ? [`${missing.length} ids; run \`bun run verification\` and see the ledger.`] : missing.map((id) => `- \`${id}\``)),
  '',
].join('\n')

const target = Bun.file(join(CONFORMANCE, 'VERIFIED.md'))
if (process.argv.includes('--check')) {
  if ((await target.exists() ? await target.text() : '') !== report) {
    console.error('extend/conformance/VERIFIED.md is stale; run `bun run verification`.')
    process.exit(1)
  }
} else {
  await Bun.write(target, report)
}
console.log(`Verification: ${checked.size} of ${requirements.length} requirements, ${judgments} judgments`)
