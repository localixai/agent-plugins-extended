/** Renders `extend/conformance/CORPUS.md` from the verdicts of the corpus check. */
import { classify, shape } from './classify.ts'
import type { FileVerdict } from './check.ts'
import type { OracleError } from './oracle.ts'
import { KINDS } from './schemas.ts'

export interface PluginVerdict {
  readonly marketplace: string
  readonly name: string
  readonly files: readonly FileVerdict[]
  /** Oracle errors on no file the check validated: the plugin directory itself, or a file no schema covers. */
  readonly elsewhere: readonly OracleError[]
}

export interface Corpus {
  readonly release: string
  readonly plugins: readonly PluginVerdict[]
  readonly skipped: number
  readonly noOracle: number
  /** Plugins whose oracle run found no plugin at the path, so read none of its files. */
  readonly unread: readonly string[]
}

const cell = (text: string): string => text.replaceAll('|', '\\|').replaceAll('\n', ' ').slice(0, 220)

const isFalseReject = (file: FileVerdict): boolean => file.ours.length > 0 && file.oracle.length === 0

function perSchema(plugins: readonly PluginVerdict[]): string[] {
  const rows = ['| Schema | Files | Refused by us | False rejects | Oracle errors | Matched | Remainder |', '| --- | ---: | ---: | ---: | ---: | ---: | ---: |']
  const total = [0, 0, 0, 0, 0, 0]
  for (const kind of KINDS) {
    const files = plugins.flatMap((p) => p.files).filter((f) => f.kind === kind)
    const row = [
      files.length,
      files.filter((f) => f.ours.length > 0).length,
      files.filter(isFalseReject).length,
      files.reduce((n, f) => n + f.oracle.length, 0),
      files.reduce((n, f) => n + f.matched.length, 0),
      files.reduce((n, f) => n + f.unmatched.length, 0),
    ]
    row.forEach((value, i) => (total[i] = (total[i] ?? 0) + value))
    rows.push(`| \`${kind}.schema.json\` | ${row.join(' | ')} |`)
  }
  rows.push(`| **All** | ${total.map((n) => `**${n}**`).join(' | ')} |`)
  return rows
}

function falseRejects(plugins: readonly PluginVerdict[]): string[] {
  const rows: string[] = []
  for (const plugin of plugins) {
    for (const file of plugin.files.filter(isFalseReject)) {
      const ours = file.ours.slice(0, 3).map((e) => `\`${e.path || '(root)'}\` ${e.message}`).join('; ')
      rows.push(`| ${plugin.marketplace}/${plugin.name} | \`${file.file}\` | ${cell(ours)} | no error |`)
    }
  }
  if (rows.length === 0) return ['None.']
  return ['| Plugin | File | Our error | Oracle |', '| --- | --- | --- | --- |', ...rows]
}

function remainder(plugins: readonly PluginVerdict[]): string[] {
  const unmatched = plugins.flatMap((p) => [...p.files.flatMap((f) => f.unmatched), ...p.elsewhere])
  const byKind = new Map<string, Map<string, number>>()
  for (const error of unmatched) {
    const kind = classify(error.message, error.path)
    const shapes = byKind.get(kind) ?? new Map<string, number>()
    const key = `${error.path.replace(/\d+/g, 'N')}: ${shape(error.message)}`
    shapes.set(key, (shapes.get(key) ?? 0) + 1)
    byKind.set(kind, shapes)
  }
  const lines: string[] = ['| Kind | Errors |', '| --- | ---: |']
  const kinds = [...byKind].sort(([, a], [, b]) => total(b) - total(a))
  for (const [kind, shapes] of kinds) lines.push(`| ${cell(kind)} | ${total(shapes)} |`)
  for (const [kind, shapes] of kinds) {
    lines.push('', `### ${kind}`, '', '| Path: message | Errors |', '| --- | ---: |')
    for (const [key, count] of [...shapes].sort(([, a], [, b]) => b - a)) lines.push(`| ${cell(key)} | ${count} |`)
  }
  return lines
}

const total = (shapes: ReadonlyMap<string, number>): number => [...shapes.values()].reduce((a, b) => a + b, 0)

function ignored(plugins: readonly PluginVerdict[]): string[] {
  const counts = new Map<string, { files: Set<string> }>()
  for (const plugin of plugins) {
    for (const file of plugin.files) {
      for (const error of file.ignored) {
        const key = `\`${file.kind}\` | \`${error.path.split('.')[0] || '(root)'}\``
        const row = counts.get(key) ?? { files: new Set<string>() }
        row.files.add(`${plugin.name}/${file.file}`)
        counts.set(key, row)
      }
    }
  }
  if (counts.size === 0) return ['None.']
  return [
    '| Schema | Field | Files |',
    '| --- | --- | ---: |',
    ...[...counts].sort(([, a], [, b]) => b.files.size - a.files.size).map(([key, row]) => `| ${key} | ${row.files.size} |`),
  ]
}

export function renderCorpus({ release, plugins, skipped, noOracle, unread }: Corpus): string {
  const files = plugins.flatMap((p) => p.files)
  return [
    '# Corpus check',
    '',
    `Generated by \`bun run corpus\` in \`extend/tools/\`; do not edit. Every file a schema of`,
    '`extend/schemas/1.1.0/claude-code/` covers, in every plugin of the official and community',
    `marketplaces, validated with that schema and compared, file by file, with the errors Claude Code`,
    `${release}'s own \`claude plugin validate\` reports for the plugin (W4).`,
    '',
    `- Plugins checked: ${plugins.length} (${skipped} not fetched, ${noOracle} without an oracle run)`,
    `- Plugins the oracle found nothing to read in (no manifest and no components): ${unread.length}`,
    `- Files checked: ${files.length}`,
    `- False rejects (we refuse a file the oracle has no error for): ${files.filter(isFalseReject).length}`,
    `- Refusals of ours that no oracle error on the same file confirms: ${files.reduce((n, f) => n + f.unconfirmed.length, 0)}`,
    `- Oracle errors matched by ours: ${files.reduce((n, f) => n + f.matched.length, 0)}`,
    `- Oracle errors left (remainder): ${files.reduce((n, f) => n + f.unmatched.length, 0) + plugins.reduce((n, p) => n + p.elsewhere.length, 0)}`,
    '',
    'An oracle error is matched when one of ours on the same file names the same field, or a part',
    'or a whole of it. The remainder is what a JSON Schema does not state (a path on disk, a reference',
    'across files, a validator policy) and, under `expressible`, what our schemas could state and do',
    'not yet.',
    '',
    '## Per schema',
    '',
    ...perSchema(plugins),
    '',
    '## False rejects',
    '',
    ...falseRejects(plugins),
    '',
    '## Values Claude Code ignores',
    '',
    'Frontmatter, themes and plugin default settings never fail for a value: Claude Code drops a',
    'value of the wrong type and loads the file, so their schemas accept it and state the values that',
    'take effect in `$defs/effective`. These are the values of the corpus that `$defs/effective`',
    'refuses, counted as files per field; none is a false reject.',
    '',
    ...ignored(plugins),
    '',
    '## Remainder by kind',
    '',
    ...remainder(plugins),
    '',
  ].join('\n')
}
