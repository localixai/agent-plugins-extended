/**
 * Writes the chapter table of `extend/spec/judgments.md` from the "Judgments" tables of the
 * chapters, so the index never drifts from the rows: each file's title, its judgment ids in
 * ranges (`J7.30–J7.41, J7.43`), and the count. `--check` fails on a stale index or on an id that
 * two files both define.
 *
 *   bun run judgments [--check]
 */
import { readdir } from 'node:fs/promises'
import { join, relative } from 'node:path'
import { SPEC } from './paths.ts'

const ROW = /^\| (J(\d+)\.(\d+)) \|/gm
const MARK = '| Chapter | Judgments | Count |'

function ranges(numbers: readonly number[], chapter: string): string {
  const parts: string[] = []
  let start = numbers[0]
  for (let index = 1; index <= numbers.length; index += 1) {
    const previous = numbers[index - 1]
    const current = numbers[index]
    if (start === undefined || previous === undefined) break
    if (current === previous + 1) continue
    parts.push(start === previous ? `J${chapter}.${start}` : `J${chapter}.${start}–J${chapter}.${previous}`)
    start = current
  }
  return parts.join(', ')
}

const folder = join(SPEC, '1.1.0')
const files = (await readdir(folder, { recursive: true, withFileTypes: true }))
  .filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
  .map((entry) => join(entry.parentPath, entry.name))
  .sort()

const seen = new Map<string, string>()
const duplicates: string[] = []
const rows: string[] = []
let total = 0
for (const file of files) {
  const text = await Bun.file(file).text()
  const ids = [...text.matchAll(ROW)]
  if (ids.length === 0) continue
  const name = relative(folder, file)
  for (const [, id = ''] of ids) {
    const other = seen.get(id)
    if (other !== undefined && other !== name) duplicates.push(`${id}: ${other} and ${name}`)
    seen.set(id, name)
  }
  const chapter = ids[0]?.[2] ?? ''
  const numbers = [...new Set(ids.map((match) => Number(match[3])))].sort((a, b) => a - b)
  const title = (text.match(/^# (.+)$/m)?.[1] ?? name).replace(/\|/g, '\\|')
  rows.push(`| [${title}](1.1.0/${name}#judgments) | ${ranges(numbers, chapter)} | ${numbers.length} |`)
  total += numbers.length
}
if (duplicates.length > 0) {
  console.error('Judgment ids defined twice:')
  for (const line of duplicates) console.error(`  ${line}`)
  process.exit(1)
}

const target = Bun.file(join(SPEC, 'judgments.md'))
const current = await target.text()
const head = current.includes(MARK) ? current.slice(0, current.indexOf(MARK)) : current.slice(0, current.indexOf('| Chapter |'))
const next = `${head}${MARK}\n| --- | --- | ---: |\n${rows.join('\n')}\n\n${total} judgments in all; generated by \`bun run judgments\`.\n`
if (process.argv.includes('--check')) {
  if (current !== next) {
    console.error('extend/spec/judgments.md is stale; run `bun run judgments`.')
    process.exit(1)
  }
} else {
  await Bun.write(target, next)
}
console.log(`Judgments: ${total} in ${rows.length} files`)
