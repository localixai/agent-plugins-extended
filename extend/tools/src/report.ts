/** Renders `extend/conformance/REPORT.md` from the requirements and the markers found. */

export interface Coverage {
  readonly release: string
  readonly requirements: readonly { readonly id: string; readonly category: string }[]
  readonly covered: ReadonlySet<string>
  /** Ids where the specification follows Claude Code's behaviour over its docs (E4a). */
  readonly deviates: ReadonlySet<string>
  /** `page | section` of documented behaviour stated beyond the requirement snapshot (C4). */
  readonly beyond: ReadonlySet<string>
  readonly byFile: ReadonlyMap<string, readonly string[]>
}

function share(part: number, whole: number): string {
  return whole === 0 ? '—' : `${((part / whole) * 100).toFixed(1)}%`
}

function categoryRows({ requirements, covered, deviates }: Coverage): string[] {
  const totals = new Map<string, { all: number; stated: number; deviate: number }>()
  for (const { id, category } of requirements) {
    const row = totals.get(category) ?? { all: 0, stated: 0, deviate: 0 }
    row.all += 1
    if (covered.has(id)) row.stated += 1
    if (deviates.has(id)) row.deviate += 1
    totals.set(category, row)
  }
  return [...totals]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([name, { all, stated, deviate }]) =>
        `| ${name} | ${stated} | ${deviate} | ${all} | ${share(stated, all)} |`,
    )
}

function deviationRows({ deviates }: Coverage): string[] {
  return deviates.size === 0 ? ['None.'] : [...deviates].sort().map((id) => `- \`${id}\``)
}

function beyondRows({ beyond }: Coverage): string[] {
  return beyond.size === 0 ? ['None.'] : [...beyond].sort().map((cite) => `- ${cite}`)
}

function fileRows({ byFile }: Coverage): string[] {
  return [...byFile]
    .filter(([, ids]) => ids.length > 0)
    .map(([file, ids]) => `| \`${file}\` | ${new Set(ids).size} |`)
}

export function renderReport(coverage: Coverage): string {
  const { release, requirements, covered, deviates } = coverage
  return [
    '# Conformance report',
    '',
    `Generated by \`bun run coverage\` (in \`extend/tools/\`) from \`requirements.json\` (Claude`,
    `Code ${release}) and the \`<!-- req: … -->\` markers in \`extend/spec/\`. A requirement is`,
    'stated when a normative paragraph names it. Do not edit by hand.',
    '',
    `**Stated: ${share(covered.size, requirements.length)} (${covered.size} of ${requirements.length} requirements).**`,
    `Deviations: ${deviates.size} — where the text follows Claude Code's observed behaviour over its`,
    'documentation, each with a judgment and oracle runs (E4a); a deviation is not counted as stated.',
    '',
    '| Category | Stated | Deviate | Total | Stated share |',
    '| --- | ---: | ---: | ---: | ---: |',
    ...categoryRows(coverage),
    '',
    '## Deviations',
    '',
    ...deviationRows(coverage),
    '',
    `## Beyond the requirement snapshot (${coverage.beyond.size})`,
    '',
    'Documented behaviour a plugin can observe that the snapshot\'s scope left out (`completeness/scope.md`),',
    'stated with a `docs:` marker that names the page and section (C4). Not counted as stated.',
    '',
    ...beyondRows(coverage),
    '',
    '## Markers per file',
    '',
    '| File | Requirements |',
    '| --- | ---: |',
    ...fileRows(coverage),
    '',
  ].join('\n')
}
